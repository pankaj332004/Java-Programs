package basics;

public class updatingShortcut {
    public static void main(String[] args) {
        int x = 5;
        System.out.println(x);
        x +=7; // x=x+7
        System.out.println(x);
        x -=2; // x=x-2
        System.out.println(x);
        x *= 5; //x=x*5
        System.out.println(x);
        x/=5; // x=x/5;
        System.out.println(x);

    }
}
