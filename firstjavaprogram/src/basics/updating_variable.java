package basics;

public class updating_variable {
    public static void main(String[] args ){
        int x;
        x = 8;
        System.out.println(x);
        x = 10; //Updating the value
        System.out.println(x);
        x = x + 6;
        System.out.println(x);
        x = x - 18;
        System.out.println(x);
        x=x*-4;
        System.out.println(x);
        x=x/2;
        System.out.println(x);

    }
}
