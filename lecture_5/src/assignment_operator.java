public class assignment_operator {
    public static void main(String[] args) {
        int p=10;
        int q;
        q=p;
        System.out.println(q);
        q+=p;
        System.out.println(q);
        p-=q;
        System.out.println(p);
        q/=p;
        System.out.println(q);
        q*=p;
        System.out.println(q);
    }
}
