public class unary_operators {
    public static void main(String[] args) {
        int p=20, q=5;
        System.out.println(p+q);
        System.out.println(p-q);
        System.out.println(p++);
        System.out.println(++p);
        System.out.println(--q);
        System.out.println(q--);
        System.out.println(--q);
    }
}
